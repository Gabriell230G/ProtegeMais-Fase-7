-- =====================================================================
--  ETAPA 2  .  ZONA_EXCLUSAO
--  Perimetro de medida protetiva. A zona pertence ao servidor, nunca ao
--  aparelho: a tornozeleira informa apenas onde esta, e quem decide se
--  aquilo e uma violacao e o banco. Um dispositivo que soubesse o raio
--  poderia ser usado para localizar a pessoa protegida, bastando andar e
--  observar o numero diminuir.
-- =====================================================================
CREATE TABLE ZONA_EXCLUSAO (
    id              NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY,
    processo        VARCHAR2(30)  NOT NULL,
    tornozeleira    VARCHAR2(40)  NOT NULL,
    lat_protegida   NUMBER(10,7)  NOT NULL,
    lng_protegida   NUMBER(10,7)  NOT NULL,
    raio_metros     NUMBER(6)     DEFAULT 500 NOT NULL,
    ativa           NUMBER(1)     DEFAULT 1   NOT NULL,
    dentro_do_perimetro NUMBER(1)    DEFAULT 0   NOT NULL,
    ultimo_alerta_em TIMESTAMP,

    CONSTRAINT zona_exclusao_pk PRIMARY KEY (id),

    -- Um aparelho vigia um perimetro de cada vez. Sem esta unicidade, duas
    -- zonas ativas para a mesma tornozeleira gerariam dois alertas para o
    -- mesmo passo, e a central perderia a confianca no alerta.
    CONSTRAINT zona_exclusao_uk_torn UNIQUE (tornozeleira),

    CONSTRAINT ck_zona_raio  CHECK (raio_metros BETWEEN 50 AND 20000),
    CONSTRAINT ck_zona_lat   CHECK (lat_protegida BETWEEN -90  AND 90),
    CONSTRAINT ck_zona_lng   CHECK (lng_protegida BETWEEN -180 AND 180),
    CONSTRAINT ck_zona_ativa CHECK (ativa IN (0,1)),
    CONSTRAINT ck_zona_dentro CHECK (dentro_do_perimetro IN (0,1))
);

COMMENT ON TABLE  ZONA_EXCLUSAO                  IS 'Perimetro de aproximacao proibida vinculado a uma medida protetiva';
COMMENT ON COLUMN ZONA_EXCLUSAO.processo         IS 'Numero do processo judicial que determinou a medida';
COMMENT ON COLUMN ZONA_EXCLUSAO.tornozeleira     IS 'Identificador OPACO do monitor eletronico. Nao identifica pessoa';
COMMENT ON COLUMN ZONA_EXCLUSAO.raio_metros      IS 'Distancia minima em metros. Fica no servidor, nunca e devolvida ao aparelho';
COMMENT ON COLUMN ZONA_EXCLUSAO.dentro_do_perimetro IS '1 quando a ultima telemetria ja estava dentro do raio. Evita alerta repetido a cada ping';
COMMENT ON COLUMN ZONA_EXCLUSAO.ultimo_alerta_em IS 'Instante do ultimo alerta aberto. Base do cooldown de 600 segundos';

-- A telemetria chega a cada ping e sempre pergunta a mesma coisa: existe
-- zona ativa para esta tornozeleira? O indice unico acima ja responde.

-- =====================================================================
--  ETAPA 3  .  PONTO_TOTEM
--  Cadastro dos totens instalados em equipamentos publicos. O totem nao
--  informa onde esta: o lugar vem daqui. Um aparelho parafusado numa
--  parede que pudesse declarar a propria coordenada permitiria que
--  alguem com acesso fisico fizesse denuncias aparecerem em qualquer
--  endereco do pais, e o mapa do painel, que orienta o deslocamento das
--  equipes, passaria a ser preenchido por quem tem uma chave de fenda.
-- =====================================================================
CREATE TABLE PONTO_TOTEM (
    id           NUMBER(19)     GENERATED BY DEFAULT AS IDENTITY,
    dispositivo  VARCHAR2(40)   NOT NULL,
    local_instalacao VARCHAR2(120) NOT NULL,
    estado       CHAR(2)        NOT NULL,
    cidade       VARCHAR2(80)   NOT NULL,
    latitude     NUMBER(10,7)   NOT NULL,
    longitude    NUMBER(10,7)   NOT NULL,
    ativo        NUMBER(1)      DEFAULT 1 NOT NULL,

    CONSTRAINT ponto_totem_pk     PRIMARY KEY (id),
    CONSTRAINT ponto_totem_uk     UNIQUE (dispositivo),

    CONSTRAINT ck_totem_lat   CHECK (latitude  BETWEEN -90  AND 90),
    CONSTRAINT ck_totem_lng   CHECK (longitude BETWEEN -180 AND 180),
    CONSTRAINT ck_totem_ativo CHECK (ativo IN (0,1)),
    CONSTRAINT ck_totem_uf    CHECK (estado = UPPER(estado))
);

COMMENT ON TABLE  PONTO_TOTEM             IS 'Totens de atendimento instalados em equipamentos publicos';
COMMENT ON COLUMN PONTO_TOTEM.dispositivo IS 'Identificador OPACO do equipamento. Nao identifica pessoa';
COMMENT ON COLUMN PONTO_TOTEM.local_instalacao IS 'Ponto de instalacao exibido no painel e gravado no caso';
COMMENT ON COLUMN PONTO_TOTEM.latitude    IS 'Coordenada da INSTALACAO, nunca informada pelo aparelho';
COMMENT ON COLUMN PONTO_TOTEM.ativo       IS '0 retira o totem de operacao sem apagar os casos ja abertos por ele';

