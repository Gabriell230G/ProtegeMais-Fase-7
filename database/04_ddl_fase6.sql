-- ---------------------------------------------------------------------
--  EVENTO_IOT
--
--  Uma tabela para as tres origens previstas, e nao uma por aparelho.
--  A alternativa seria criar EVENTO_SOS, EVENTO_GEOFENCE e EVENTO_TOTEM,
--  o que triplicaria o modelo para guardar praticamente as mesmas colunas
--  e obrigaria o painel a unir tres consultas so para montar uma linha
--  do tempo. O discriminador `origem` resolve isso com um CHECK.
--
--  O que esta tabela deliberadamente NAO tem: qualquer coluna capaz de
--  identificar a pessoa que carrega o aparelho. O vinculo entre aparelho
--  e cidadao, quando existir, vive fora daqui e sob controle de acesso.
-- ---------------------------------------------------------------------
CREATE TABLE EVENTO_IOT (
    id                NUMBER(12)     GENERATED ALWAYS AS IDENTITY,
    origem            VARCHAR2(10)   NOT NULL,
    dispositivo       VARCHAR2(40)   NOT NULL,
    latitude          NUMBER(9,6),
    longitude         NUMBER(9,6),
    bateria           NUMBER(3),
    recebido_em       TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    situacao          VARCHAR2(12)   DEFAULT 'ACEITO'     NOT NULL,
    protocolo_gerado  VARCHAR2(20),
    detalhe           VARCHAR2(200),

    CONSTRAINT evento_iot_pk        PRIMARY KEY (id),

    CONSTRAINT ck_evento_iot_origem   CHECK (origem   IN ('SOS','GEOFENCE','TOTEM')),
    CONSTRAINT ck_evento_iot_situacao CHECK (situacao IN ('ACEITO','DUPLICADO','DESCARTADO')),
    CONSTRAINT ck_evento_iot_bateria  CHECK (bateria IS NULL OR bateria BETWEEN 0 AND 100),
    CONSTRAINT ck_evento_iot_lat      CHECK (latitude  IS NULL OR latitude  BETWEEN -90  AND 90),
    CONSTRAINT ck_evento_iot_lng      CHECK (longitude IS NULL OR longitude BETWEEN -180 AND 180),

    -- Coordenada so faz sentido completa. Guardar so a latitude seria
    -- guardar um dado que nao responde pergunta nenhuma.
    CONSTRAINT ck_evento_iot_coord    CHECK ((latitude IS NULL     AND longitude IS NULL)
                                          OR (latitude IS NOT NULL AND longitude IS NOT NULL))
);

COMMENT ON TABLE  EVENTO_IOT                  IS 'Eventos recebidos de dispositivos fisicos: botao de panico, tornozeleira com geofencing e totem publico';
COMMENT ON COLUMN EVENTO_IOT.origem           IS 'SOS, GEOFENCE ou TOTEM. Discriminador do barramento';
COMMENT ON COLUMN EVENTO_IOT.dispositivo      IS 'Identificador OPACO do aparelho. Nao identifica pessoa';
COMMENT ON COLUMN EVENTO_IOT.situacao         IS 'ACEITO gerou caso; DUPLICADO e repique do mesmo aparelho; DESCARTADO falhou validacao';
COMMENT ON COLUMN EVENTO_IOT.protocolo_gerado IS 'Protocolo da denuncia aberta por este evento, quando houver';
COMMENT ON COLUMN EVENTO_IOT.detalhe          IS 'Texto curto e nao sensivel sobre o processamento do evento';

-- A regra de repique consulta o ultimo evento ACEITO de um aparelho. Sem
-- este indice, cada acionamento faria varredura completa da tabela, e o
-- custo cresceria junto com o numero de dispositivos em campo.
CREATE INDEX idx_evento_iot_disp   ON EVENTO_IOT (dispositivo, situacao, recebido_em DESC);

-- A tela do painel lista os eventos mais recentes, opcionalmente por origem.
CREATE INDEX idx_evento_iot_recente ON EVENTO_IOT (origem, recebido_em DESC);

